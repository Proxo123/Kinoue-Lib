"""Build a dependency-free Luau bundle and Roblox importable ModuleScript."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
DIST = ROOT / "dist"


def module_name(path):
    relative = path.relative_to(SRC).with_suffix("").as_posix()
    return "init" if relative == "init" else relative


def resolve(current, expression):
    # A directory's init ModuleScript owns its children in Rojo.
    parts = [] if current == "init" else current.split("/")
    for segment in expression.split(".")[1:]:
        if segment == "Parent":
            if parts:
                parts.pop()
        else:
            parts.append(segment)
    return "/".join(parts) or "init"


def bundle():
    paths = sorted(SRC.rglob("*.luau"), key=lambda p: p.relative_to(SRC).as_posix())
    modules = {module_name(p): p.read_text(encoding="utf-8") for p in paths}
    chunks = ["-- Generated by tools/build.py; edit src/ instead.\nlocal __factories, __cache, __loading = {}, {}, {}\nlocal __require\n"]
    for name, source in modules.items():
        def replace(match):
            target = resolve(name, match[1])
            if target not in modules:
                raise ValueError(f"{name}: missing dependency {target}")
            return f"__require({json.dumps(target)})"
        source = re.sub(r"require\((script(?:\.[A-Za-z_]\w*)+)\)", replace, source)
        chunks.append(f"__factories[{json.dumps(name)}] = function()\n{source}\nend\n")
    chunks.append("""
__require = function(name)
    if __cache[name] ~= nil then return __cache[name] end
    assert(not __loading[name], "Circular dependency: " .. name)
    local factory = assert(__factories[name], "Unknown module: " .. name)
    __loading[name] = true
    local value = factory()
    __loading[name] = nil
    __cache[name] = value
    return value
end
return __require("init")
""")
    return "".join(chunks)


def item(parent, class_name, name, source=None):
    node = ET.SubElement(parent, "Item", {"class": class_name, "referent": "RBX" + str(len(list(parent.iter("Item")))) + "_" + name})
    props = ET.SubElement(node, "Properties")
    ET.SubElement(props, "string", {"name": "Name"}).text = name
    if source is not None:
        ET.SubElement(props, "ProtectedString", {"name": "Source"}).text = source
    return node


def write_xml(path, tree):
    ET.indent(tree, space="  ")
    ET.ElementTree(tree).write(path, encoding="utf-8", xml_declaration=True)


def main():
    DIST.mkdir(exist_ok=True)
    source = bundle()
    demo = (ROOT / "examples/Booga.client.luau").read_text(encoding="utf-8")
    (DIST / "BoogaUI.lua").write_text(source, encoding="utf-8", newline="\n")
    embedded_demo = "local Library = (function()\n" + source + "\nend)()\n" + demo.split("\n", 1)[1]
    (DIST / "BoogaDemo.lua").write_text(embedded_demo, encoding="utf-8", newline="\n")
    model = ET.Element("roblox", {"version": "4"})
    item(model, "ModuleScript", "BoogaUI", source)
    write_xml(DIST / "BoogaUI.rbxmx", model)
    place = ET.Element("roblox", {"version": "4"})
    replicated = item(place, "ReplicatedStorage", "ReplicatedStorage")
    item(replicated, "ModuleScript", "BoogaUI", source)
    starter = item(place, "StarterPlayer", "StarterPlayer")
    scripts = item(starter, "StarterPlayerScripts", "StarterPlayerScripts")
    item(scripts, "LocalScript", "BoogaDemo", demo)
    item(place, "Workspace", "Workspace")
    write_xml(DIST / "BoogaDemo.rbxlx", place)
    print("Built BoogaUI.lua, BoogaDemo.lua, BoogaUI.rbxmx, BoogaDemo.rbxlx")


if __name__ == "__main__":
    main()
